    """Result of executing a cleaning plan."""
    plan: CleanPlan
    df_clean: pl.DataFrame
    changes: list[ChangeRecord] = field(default_factory=list)
    rows_before: int = 0
    rows_after: int = 0
    total_changes: int = 0
