import time


async def execute_clean_plan(
    df: pl.DataFrame,
    plan: CleanPlan,
) -> CleanResult:
    """Execute a cleaning plan on the data."""
    start_time = time.time()
    df_clean = df.clone()
    all_changes: list[ChangeRecord] = []
    rows_before = len(df)

    for step in plan.steps:
        step.status = "running"
        try:
            op_func = PRESET_OPERATIONS.get(step.operation)
            if op_func is None:
                step.status = "skipped"
                step.error = f"Unknown operation: {step.operation}"
                continue

            df_clean, changes = op_func(df_clean, step.config)
            step.rows_affected = len(changes)
            step.status = "done"

            # Tag changes with step_id
            for c in changes:
                c.step_id = step.step_id

            all_changes.extend(changes)

        except Exception as e:
            step.status = "failed"
            step.error = str(e)

    elapsed_ms = int((time.time() - start_time) * 1000)

    return CleanResult(
        plan=plan,
        df_clean=df_clean,
        changes=all_changes,
        rows_before=rows_before,
        rows_after=len(df_clean),
        total_changes=len(all_changes),
        execution_time_ms=elapsed_ms,
    )


