def apply_dedup(df: pl.DataFrame, config: dict[str, Any] | None = None) -> tuple[pl.DataFrame, list[ChangeRecord]]:
    """Remove exact duplicate rows."""
    config = config or {}
    method = config.get("method", "exact")
    keep = config.get("keep", "first")

    original_count = len(df)

    if method == "exact":
        df_clean = df.unique(keep=keep)
    else:
        # Fuzzy dedup — use specified columns
        columns = config.get("columns")
        if columns:
            df_clean = df.unique(subset=columns, keep=keep)
        else:
            df_clean = df.unique(keep=keep)

    removed = original_count - len(df_clean)
    changes = [
        ChangeRecord(
            row_index=i,
            column="__row__",
            before="duplicate",
            after="removed",
            operation="dedup",
            step_id="dedup",
        )
        for i in range(removed)
    ]

    return df_clean, changes


def apply_missing_fill(
    df: pl.DataFrame, config: dict[str, Any] | None = None
) -> tuple[pl.DataFrame, list[ChangeRecord]]:
    """Fill or drop missing values."""
    config = config or {}
    strategy = config.get("strategy", "drop")  # drop | fill_mean | fill_median | fill_mode | fill_value
    columns = config.get("columns")
    fill_value = config.get("fill_value")

    target_cols = columns or [c for c in df.columns if df[c].null_count() > 0]
    changes: list[ChangeRecord] = []

    if strategy == "drop":
        before = len(df)
        df_clean = df.drop_nulls(subset=target_cols)
        removed = before - len(df_clean)
        for i in range(removed):
            changes.append(ChangeRecord(
                row_index=i, column="__row__", before="had nulls",
                after="dropped", operation="missing_drop", step_id="missing",
            ))
    else:
        df_clean = df.clone()
        for col in target_cols:
            if col not in df_clean.columns:
                continue
            series = df_clean[col]
            null_mask = series.is_null()
            null_count = null_mask.sum()
            if null_count == 0:
                continue

            if strategy == "fill_mean" and series.dtype in (pl.Float64, pl.Float32, pl.Int64, pl.Int32):
                fill = series.mean()
            elif strategy == "fill_median" and series.dtype in (pl.Float64, pl.Float32, pl.Int64, pl.Int32):
                fill = series.median()
            elif strategy == "fill_mode":
                fill = series.mode()[0] if len(series.mode()) > 0 else None
            elif strategy == "fill_value":
                fill = fill_value
            else:
                continue

            if fill is not None:
                # Record changes
                null_indices = df_clean.filter(null_mask).row_nr if "row_nr" in df_clean.columns else list(range(null_count))
                for idx in range(null_count):
                    changes.append(ChangeRecord(
                        row_index=idx, column=col, before=None,
                        after=fill, operation="missing_fill", step_id="missing",
                    ))
                df_clean = df_clean.with_columns(
                    pl.col(col).fill_null(fill).alias(col)
                )

    return df_clean, changes


def apply_outlier_filter(
    df: pl.DataFrame, config: dict[str, Any] | None = None
) -> tuple[pl.DataFrame, list[ChangeRecord]]:
    """Filter outlier values using IQR method."""
    config = config or {}
    columns = config.get("columns")
    method = config.get("method", "iqr")  # iqr | zscore
    threshold = config.get("threshold", 1.5)

    numeric_cols = columns or [
        c for c in df.columns
        if df[c].dtype in (pl.Float64, pl.Float32, pl.Int64, pl.Int32)
    ]

    mask = pl.lit(True)
    for col in numeric_cols:
        if col not in df.columns:
            continue
        series = df[col]
        q1 = series.quantile(0.25)
        q3 = series.quantile(0.75)
        if q1 is not None and q3 is not None:
            iqr = q3 - q1
            lower = q1 - threshold * iqr
            upper = q3 + threshold * iqr
            mask = mask & (pl.col(col) >= lower) & (pl.col(col) <= upper)

    df_clean = df.filter(mask)
    removed = len(df) - len(df_clean)

    changes = [
        ChangeRecord(
            row_index=i, column="__row__", before="outlier",
            after="removed", operation="outlier_filter", step_id="outlier",
        )
        for i in range(removed)
    ]

    return df_clean, changes


def apply_text_clean(
    df: pl.DataFrame, config: dict[str, Any] | None = None
) -> tuple[pl.DataFrame, list[ChangeRecord]]:
    """Clean text fields: strip whitespace, normalize, etc."""
    config = config or {}
    columns = config.get("columns")
    operations = config.get("operations", ["strip", "normalize_space"])

    text_cols = columns or [
        c for c in df.columns if df[c].dtype in (pl.Utf8, pl.String)
    ]

    df_clean = df.clone()
    changes: list[ChangeRecord] = []

    for col in text_cols:
        if col not in df_clean.columns:
            continue

        expr = pl.col(col)
        if "strip" in operations:
            expr = expr.str.strip_chars()
        if "normalize_space" in operations:
            expr = expr.str.replace_all(r"\s+", " ")
        if "lowercase" in operations:
            expr = expr.str.to_lowercase()
        if "remove_special" in operations:
            expr = expr.str.replace_all(r"[^\w\s@.\-]", "")

        # Count changes
        before = df_clean[col].to_list()
        df_clean = df_clean.with_columns(expr.alias(col))
        after = df_clean[col].to_list()

        for i, (b, a) in enumerate(zip(before, after)):
            if b != a:
                changes.append(ChangeRecord(
                    row_index=i, column=col, before=b,
                    after=a, operation="text_clean", step_id="text",
                ))

    return df_clean, changes


def apply_date_standardize(
    df: pl.DataFrame, config: dict[str, Any] | None = None
) -> tuple[pl.DataFrame, list[ChangeRecord]]:
    """Standardize date columns to ISO format."""
    config = config or {}
    columns = config.get("columns")
    target_format = config.get("target_format", "%Y-%m-%d")

    date_cols = columns or [
        c for c in df.columns
        if df[c].dtype in (pl.Utf8, pl.String)
    ]

    df_clean = df.clone()
    changes: list[ChangeRecord] = []

    from datetime import datetime

    date_formats = [
        "%Y-%m-%d", "%m/%d/%Y", "%d/%m/%Y", "%Y/%m/%d",
        "%d-%m-%Y", "%m-%d-%Y", "%Y.%m.%d", "%d.%m.%Y",
        "%B %d, %Y", "%b %d, %Y",
    ]

    for col in date_cols:
        if col not in df_clean.columns:
            continue
        if df_clean[col].dtype not in (pl.Utf8, pl.String):
            continue

        # Try to detect if this is actually a date column
        sample = df_clean[col].drop_nulls().head(20).to_list()
        is_date = False
        detected_fmt = None

        for fmt in date_formats:
            try:
                matches = sum(
                    1 for v in sample
                    if _safe_parse_date(str(v), fmt) is not None
                )
                if matches / max(len(sample), 1) > 0.6:
                    is_date = True
                    detected_fmt = fmt
                    break
            except Exception:
                continue

        if not is_date or detected_fmt is None:
            continue

        # Convert
        before_values = df_clean[col].to_list()
        converted = []
        for v in before_values:
            if v is None:
                converted.append(None)
            else:
                parsed = _safe_parse_date(str(v), detected_fmt)
                converted.append(parsed.strftime(target_format) if parsed else str(v))

        df_clean = df_clean.with_columns(
            pl.Series(col, converted, dtype=pl.Utf8)
        )

        for i, (b, a) in enumerate(zip(before_values, converted)):
            if b is not None and str(b) != a:
                changes.append(ChangeRecord(
                    row_index=i, column=col, before=str(b),
                    after=a, operation="date_standardize", step_id="date",
                ))

    return df_clean, changes


def _safe_parse_date(value: str, fmt: str):
    from datetime import datetime
    try:
        return datetime.strptime(value.strip(), fmt)
    except (ValueError, AttributeError):
        return None


