def _parse_json_robust(content: str) -> dict:
    """Parse JSON from LLM output, handling truncation and formatting issues."""
    import re as _re

    # 1. Try direct parse
    try:
        return json.loads(content)
    except json.JSONDecodeError:
        pass

    # 2. Try to find a complete JSON object with "steps" key
    json_match = _re.search(r'\{[\s\S]*"steps"[\s\S]*\}', content)
    if json_match:
        try:
            return json.loads(json_match.group())
        except json.JSONDecodeError:
            pass

    # 3. Truncated response — try to repair by closing open brackets
    #    Find the last complete step object and close everything after it
    last_complete_step = content.rfind('"step_id"')
    if last_complete_step > 0:
        # Find the closing } of this step object
        brace_count = 0
        i = last_complete_step
        while i < len(content):
            if content[i] == '{':
                brace_count += 1
            elif content[i] == '}':
                brace_count -= 1
                if brace_count <= 0:
                    # Found the end of the last complete step
                    truncated = content[:i + 1]
                    # Close the steps array and outer object
                    truncated = truncated.rstrip().rstrip(',')
                    truncated += ']\n}'
                    try:
                        return json.loads(truncated)
                    except json.JSONDecodeError:
                        pass
                    break
            i += 1

    # 4. Last resort — extract whatever JSON-like structure exists
    #    Try truncating at the last complete } pair
    for end_pos in range(len(content) - 1, 0, -1):
        candidate = content[:end_pos + 1]
        # Count brackets
        opens = candidate.count('{') + candidate.count('[')
        closes = candidate.count('}') + candidate.count(']')
        if closes >= opens - 2:
            # Try closing remaining open brackets
            remaining = []
            stack = []
            for ch in candidate:
                if ch in ('{', '['):
                    stack.append(ch)
                elif ch in ('}', ']'):
                    if stack:
                        stack.pop()
            for opener in reversed(stack):
                remaining.append(']' if opener == '[' else '}')
            repaired = candidate.rstrip().rstrip(',') + ''.join(remaining)
            try:
                result = json.loads(repaired)
                if isinstance(result, dict) and 'steps' in result:
                    return result
            except json.JSONDecodeError:
                continue

    raise ValueError(f"AI returned invalid JSON. Raw response: {content[:500]}")


async def generate_clean_plan(
    df: pl.DataFrame,
    profile: ProfileReport,
    instruction: str,
) -> CleanPlan:
    """Use LLM to generate a cleaning plan from natural language instruction."""
    settings = get_settings()

    # Prepare context (shared between providers)
    schema_info = []
    for col in profile.columns:
        schema_info.append({
            "name": col.name,
            "type": col.inferred_type,
            "null_pct": col.null_pct,
            "unique_pct": col.unique_pct,
            "sample_values": col.sample_values[:3],
            "issues": col.issues,
        })

    sample_rows = df.head(5).to_dicts()
    for row in sample_rows:
        for k, v in row.items():
            if not isinstance(v, (str, int, float, bool, type(None))):
                row[k] = str(v)

    issues_summary = "; ".join(
        f"[{i.severity}] {i.message}" for i in profile.issues[:10]
    )

    prompt = _CLEAN_PLAN_PROMPT.format(
        schema_json=json.dumps(schema_info, indent=2, ensure_ascii=False),
        total_rows=profile.total_rows,
        total_columns=profile.total_columns,
        health_score=profile.health_score,
        duplicate_rows=profile.duplicate_rows,
        duplicate_pct=profile.duplicate_pct,
        issues_summary=issues_summary or "None",
        sample_json=json.dumps(sample_rows, indent=2, ensure_ascii=False, default=str),
        instruction=instruction,
    )

    # Route to the configured provider
    if settings.ai_provider == "glm":
        content = await _call_glm(settings, prompt)
    elif settings.ai_provider == "anthropic":
        content = await _call_anthropic(settings, prompt)
    else:
        raise ValueError(f"Unknown AI provider: {settings.ai_provider}")

    # Parse response — extract JSON robustly
    content = content.strip()

    # Remove markdown fences if present (```json ... ``` or ``` ... ```)
    import re as _re
    md_match = _re.search(r'```(?:json)?\s*\n?(.*?)```', content, _re.DOTALL)
    if md_match:
        content = md_match.group(1).strip()

    if not content:
        raise ValueError("AI returned an empty response. Please try again.")

    plan_data = _parse_json_robust(content)

    steps = []
    for s in plan_data.get("steps", []):
        steps.append(CleanStep(
            step_id=s.get("step_id", f"step_{len(steps)}"),
            operation=s["operation"],
            description=s.get("description", ""),
            config=s.get("config", {}),
        ))

    return CleanPlan(
        steps=steps,
        reasoning=plan_data.get("reasoning", ""),
        estimated_row_reduction=plan_data.get("estimated_row_reduction", 0),
    )


async def _call_glm(settings, prompt: str) -> str:
    """Call GLM (智谱) API — OpenAI-compatible endpoint."""
    if not settings.glm_api_key:
        raise ValueError("GLM_API_KEY is not configured")

    import httpx

    url = f"{settings.glm_base_url}/chat/completions"
    headers = {
        "Authorization": f"Bearer {settings.glm_api_key}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": settings.glm_model,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You are an expert data engineer. "
                    "Always respond with valid JSON only, no markdown fences, no explanation."
                ),
            },
            {"role": "user", "content": prompt},
        ],
        "temperature": 0.3,
        "max_tokens": 16384,
        "stream": False,
    }

    last_error = None
    for attempt in range(2):  # Retry once on failure
        try:
            async with httpx.AsyncClient(timeout=120.0) as client:
                resp = await client.post(url, json=payload, headers=headers)
                resp.raise_for_status()
                data = resp.json()

            message = data["choices"][0]["message"]
            content = message.get("content", "")

            # GLM-4.5 reasoning models may put output in reasoning_content
            # If content is empty, fall back to reasoning_content
            if not content.strip():
                content = message.get("reasoning_content", "")

            if not content.strip():
                raise ValueError("GLM returned empty response")

            return content

        except (httpx.HTTPStatusError, httpx.RequestError, ValueError) as e:
            last_error = e
            if attempt == 0:
                import asyncio
                await asyncio.sleep(1)  # Brief pause before retry
                continue
            raise ValueError(f"GLM API failed after 2 attempts: {last_error}")


async def _call_anthropic(settings, prompt: str) -> str:
    """Call Anthropic Claude API."""
    if not settings.anthropic_api_key:
        raise ValueError("ANTHROPIC_API_KEY is not configured")

    import anthropic

    client = anthropic.AsyncAnthropic(api_key=settings.anthropic_api_key)
    response = await client.messages.create(
        model="claude-sonnet-4-20250514",
        max_tokens=2048,
        messages=[{"role": "user", "content": prompt}],
    )

    return response.content[0].text


